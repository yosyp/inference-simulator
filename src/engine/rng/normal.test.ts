// Beyond the required range: the far-tail branch (p < e^-25 ≈ 1.39e-11), down to the smallest
// normal double. References solve log Φ(x) = log p (a relative residual) and agree with a 700-digit
// erfinv to 1e-40.
const FAR_TAIL: readonly (readonly [number, number])[] = [
  [1.3887943864964021e-11, -6.657904643501103],
  [1e-12, -7.034483825301132],
  [1e-15, -7.941345326170997],
  [1e-20, -9.262340089798407],
  [1e-50, -14.933337534788489],
  [1e-100, -21.273453560965326],
  [1e-300, -37.0470962993612],
  [2.2250738585072014e-308, -37.5193793471445],
];

describe('normalQuantile', () => {
  it('is within 1e-8 absolute of 60-digit references over (1e-10, 1 - 1e-10)', () => {
    let worst = 0;
    for (const [p, x] of IN_RANGE) {
      expect(p).toBeGreaterThan(1e-10);
      expect(p).toBeLessThan(1 - 1e-10);
      const err = Math.abs(normalQuantile(p) - x);
      expect(err, `p = ${p}`).toBeLessThan(1e-8);
      worst = Math.max(worst, err);
    }
    // AS 241 is good to about 1e-16 relative; a mistyped coefficient shows up well above this.
    expect(worst).toBeLessThan(1e-13);
  });

  it('keeps full relative accuracy in the far tail', () => {
    for (const [p, x] of FAR_TAIL) {
      expect(Math.abs(normalQuantile(p) - x) / Math.abs(x), `p = ${p}`).toBeLessThan(1e-13);
    }
  });

  it('is antisymmetric about 0.5 and monotone', () => {
    // p and 1 - p are both exact for p = k / 2^20.
    let prev = -Infinity;
    for (let k = 1; k < 2 ** 20; k += 97) {
      const p = k / 2 ** 20;
      const x = normalQuantile(p);
      expect(x).toBeGreaterThan(prev);
      expect(normalQuantile(1 - p)).toBe(-x);
      prev = x;
    }
    expect(normalQuantile(0.5)).toBe(0);
  });

  it('is monotone across the region boundaries', () => {
    // [boundary, step]: the central/tail switch at |p - 0.5| = 0.425, and the tail/far-tail switch
    // at min(p, 1 - p) = e^-25, stepped by one ulp near 1.
    const edges = [
      [0.075, 1e-12],
      [0.925, 1e-12],
      [Math.exp(-25), 1e-15],
      [1 - Math.exp(-25), 2 ** -53],
    ] as const;
    for (const [edge, step] of edges) {
      let prev = -Infinity;
      for (let i = -1000; i <= 1000; i++) {
        const x = normalQuantile(edge + i * step);
        expect(x).toBeGreaterThanOrEqual(prev);
        prev = x;
      }
    }
  });

  it('returns ±Infinity at 0 and 1 and NaN outside [0, 1]', () => {
    expect(normalQuantile(0)).toBe(-Infinity);
    expect(normalQuantile(1)).toBe(Infinity);
    expect(normalQuantile(-0.1)).toBeNaN();
    expect(normalQuantile(1.1)).toBeNaN();
    expect(normalQuantile(NaN)).toBeNaN();
    expect(Number.isFinite(normalQuantile(Number.MIN_VALUE))).toBe(true);
    expect(Number.isFinite(normalQuantile(1 - 2 ** -53))).toBe(true);
  });
});
