// Result chunk layout (docs/00-build.md §4; 02-simulator §11). Frozen at M0: change only through the integrator.
// Columnar typed arrays throughout (K7) so chunks transfer between worker and main thread without copying.

import type { ReplicaId } from './api.ts';
import { HISTOGRAM_SPECS, type HistogramMetric } from './histogram.ts';
import type { DayIndex, SimMs } from './time.ts';

/** Series index: 0 is the fleet, r + 1 is replica r. */
export const FLEET_SERIES = 0;
export function replicaSeries(replica: ReplicaId): number {
  return replica + 1;
}

/**
 * How a scalar merges across buckets. 'sum': totals add. 'mean': time-weighted level, average it.
 * 'max': take the max. Fleet series: sums add across replicas; 'mean' levels are summed across
 * replicas too, except kvUsedFrac, which is the mean across Ready replicas.
 */
export type Aggregation = 'sum' | 'mean' | 'max';

export const SCALAR_METRICS = {
  // Levels, time-weighted over the bucket.
  kvUsedFrac: 'mean', // blocks referenced by requests ÷ pool (vLLM kv_cache_usage_perc)
  kvUsedFracMax: 'max',
  running: 'mean',
  waiting: 'mean',
  outstanding: 'mean', // router-tracked: dispatched and not finished
  readyReplicas: 'mean', // fleet series only
  // Engine totals.
  preemptions: 'sum',
  prefixQueryTokens: 'sum',
  prefixHitTokens: 'sum',
  returningQueryTokens: 'sum', // prefix lookups for turns >= 2 (tab 4)
  returningHitTokens: 'sum',
  prefillTokens: 'sum', // computed, excluding cache hits, including recompute
  recomputedPrefillTokens: 'sum', // prefill redone after preemption (tab 3)
  decodeTokens: 'sum',
  busyMs: 'sum', // time a step is executing: nvidia-smi-style utilization = busyMs / bucketMs
  flops: 'sum', // achieved: compute utilization = flops / (peak FLOPS × bucket seconds)
  evictedBlocks: 'sum',
  // Request counts.
  dispatched: 'sum',
  finished: 'sum', // requests served
  timedOut: 'sum',
  failed: 'sum',
  ttftSumMs: 'sum',
  ttftCount: 'sum',
  tpotSumMs: 'sum',
  tpotCount: 'sum',
  e2eSumMs: 'sum',
  e2eCount: 'sum',
  // Fleet only (zero in replica series).
  offered: 'sum', // arrivals at the router, including retries
  organic: 'sum', // first attempts only; amplification = offered / organic
  rejected: 'sum',
  retries: 'sum',
  abandonedSessions: 'sum',
} as const satisfies Record<string, Aggregation>;

export type ScalarMetric = keyof typeof SCALAR_METRICS;
export const SCALAR_METRIC_NAMES = Object.keys(SCALAR_METRICS) as ScalarMetric[];

/** Buckets of width bucketMs starting at startMs. Value index: bucket * series + seriesIndex. */
export interface ScalarBlock {
  startMs: SimMs;
  bucketMs: number;
  count: number;
  series: number;
  data: Record<ScalarMetric, Float32Array>;
}

/** Histogram buckets of width histBucketMs. Index: (bucket * series + seriesIndex) * bins + bin. */
export interface HistogramBlock {
  startMs: SimMs;
  bucketMs: number;
  count: number;
  series: number;
  data: Record<HistogramMetric, Uint32Array>;
}

export const REQUEST_STATE = {
  atRouter: 0,
  waiting: 1,
  prefill: 2,
  decode: 3,
  preempted: 4, // back in the waiting queue after preemption; recomputes when rescheduled
  finished: 5,
  rejected: 6,
  timedOut: 7, // client gave up; the server aborted (K8)
  failed: 8, // replica crashed
} as const;
export type RequestState = (typeof REQUEST_STATE)[keyof typeof REQUEST_STATE];

export const OUTCOME = {
  finished: REQUEST_STATE.finished,
  rejected: REQUEST_STATE.rejected,
  timedOut: REQUEST_STATE.timedOut,
  failed: REQUEST_STATE.failed,
} as const;
export type Outcome = (typeof OUTCOME)[keyof typeof OUTCOME];

/**
 * Requests that reached their outcome inside the chunk. Times are NaN when a stage was never
 * reached. Scope 'tracked' holds only the tracked analyst's requests (see DayRunInput.detail).
 */
export interface RequestBlock {
  scope: 'all' | 'tracked';
  count: number;
  id: Uint32Array;
  session: Uint32Array;
  analyst: Uint32Array;
  /** 1-based turn within the session. */
  turn: Uint16Array;
  /** 0 for the first attempt. */
  attempt: Uint8Array;
  /** -1 if never dispatched. */
  replica: Int8Array;
  /** Replica that served the session's previous turn; -1 on the first turn. Moved = prevReplica !== -1 && replica !== prevReplica. */
  prevReplica: Int8Array;
  arriveMs: Float64Array;
  dispatchMs: Float64Array;
  firstTokenMs: Float64Array;
  endMs: Float64Array;
  promptTokens: Uint32Array;
  cachedTokens: Uint32Array;
  /** Tokens generated by the end. */
  outputTokens: Uint32Array;
  preemptions: Uint16Array;
  outcome: Uint8Array;
}

/** State changes, for canvas dots. Scope as in RequestBlock. */
export interface TransitionBlock {
  scope: 'all' | 'tracked';
  count: number;
  atMs: Float64Array;
  request: Uint32Array;
  analyst: Uint32Array;
  replica: Int8Array;
  state: Uint8Array;
}

export const REPLICA_STATE = {
  ready: 0,
  crashed: 1, // dead but not yet marked down; the router still sends to it
  down: 2, // marked down
  loadingWeights: 3,
  initializingEngine: 4,
} as const;
export type ReplicaState = (typeof REPLICA_STATE)[keyof typeof REPLICA_STATE];

export interface ReplicaEvent {
  atMs: SimMs;
  replica: ReplicaId;
  state: ReplicaState;
}

/**
 * Everything a DayRun produced in [fromMs, toMs). Scalar and histogram blocks hold only complete
 * buckets, so their ranges may lag toMs by less than one bucket.
 */
export interface ResultChunk {
  day: DayIndex;
  fromMs: SimMs;
  toMs: SimMs;
  replicas: number;
  scalars: ScalarBlock;
  histograms: HistogramBlock;
  requests: RequestBlock;
  transitions: TransitionBlock;
  replicaEvents: ReplicaEvent[];
}

/** High-side rollup (01 §8): per replica per day, delivered at day N+1 12:00. */
export interface RollupRow {
  day: DayIndex;
  replica: ReplicaId;
  requestsServed: number;
  /** NaN if nothing was served. */
  meanE2eMs: number;
  /** Mean nvidia-smi-style utilization, 0..1. */
  meanNvidiaSmiUtil: number;
  deliveredAtMs: SimMs;
}

export function histogramBins(metric: HistogramMetric): number {
  return HISTOGRAM_SPECS[metric].bins;
}

export function allocScalarBlock(
  startMs: SimMs,
  bucketMs: number,
  count: number,
  series: number,
): ScalarBlock {
  const data = {} as Record<ScalarMetric, Float32Array>;
  for (const m of Object.keys(SCALAR_METRICS) as ScalarMetric[]) {
    data[m] = new Float32Array(count * series);
  }
  return { startMs, bucketMs, count, series, data };
}

export function allocHistogramBlock(
  startMs: SimMs,
  bucketMs: number,
  count: number,
  series: number,
): HistogramBlock {
  const data = {} as Record<HistogramMetric, Uint32Array>;
  for (const m of Object.keys(HISTOGRAM_SPECS) as HistogramMetric[]) {
    data[m] = new Uint32Array(count * series * HISTOGRAM_SPECS[m].bins);
  }
  return { startMs, bucketMs, count, series, data };
}

export function allocRequestBlock(scope: 'all' | 'tracked', count: number): RequestBlock {
  return {
    scope,
    count,
    id: new Uint32Array(count),
    session: new Uint32Array(count),
    analyst: new Uint32Array(count),
    turn: new Uint16Array(count),
    attempt: new Uint8Array(count),
    replica: new Int8Array(count),
    prevReplica: new Int8Array(count),
    arriveMs: new Float64Array(count).fill(NaN),
    dispatchMs: new Float64Array(count).fill(NaN),
    firstTokenMs: new Float64Array(count).fill(NaN),
    endMs: new Float64Array(count).fill(NaN),
    promptTokens: new Uint32Array(count),
    cachedTokens: new Uint32Array(count),
    outputTokens: new Uint32Array(count),
    preemptions: new Uint16Array(count),
    outcome: new Uint8Array(count),
  };
}

export function allocTransitionBlock(scope: 'all' | 'tracked', count: number): TransitionBlock {
  return {
    scope,
    count,
    atMs: new Float64Array(count),
    request: new Uint32Array(count),
    analyst: new Uint32Array(count),
    replica: new Int8Array(count),
    state: new Uint8Array(count),
  };
}

/** Buffers to list in postMessage's transfer argument. */
export function chunkTransferables(chunk: ResultChunk): ArrayBuffer[] {
  const buffers = new Set<ArrayBuffer>();
  const add = (a: { buffer: ArrayBufferLike }) => {
    if (a.buffer instanceof ArrayBuffer) buffers.add(a.buffer);
  };
  for (const a of Object.values(chunk.scalars.data)) add(a);
  for (const a of Object.values(chunk.histograms.data)) add(a);
  for (const block of [chunk.requests, chunk.transitions]) {
    for (const v of Object.values(block)) {
      if (ArrayBuffer.isView(v)) add(v);
    }
  }
  return [...buffers];
}
